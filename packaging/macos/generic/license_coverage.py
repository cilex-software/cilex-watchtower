"""Validate recorded redistribution review without inferring legal approval.

This is a structural, offline check: a reviewer maps every distributed payload
file (including code embedded in an archive/executable) to its components and
hashed notices/source evidence. It does not decide what any license permits.
"""
from __future__ import annotations

import datetime
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import urllib.parse

from closure import ClosureError, contained, inventory, sha256

SCHEMA_VERSION = 1
MAX_MANIFEST_BYTES = 16 * 1024 * 1024
ATTESTATION = 'all-distributed-components-including-embedded-code'


class LicenseCoverageError(RuntimeError):
    pass


def _fail(message):
    raise LicenseCoverageError(message)


def _keys(value, required, optional=()):
    if not isinstance(value, dict) or set(value) - set(required) - set(optional) or set(required) - set(value):
        _fail('Invalid license manifest fields; use the versioned template/schema.')


def _text(value, label):
    if not isinstance(value, str) or not value.strip() or len(value) > 4096 or any(ord(c) < 32 for c in value):
        _fail('Missing or invalid license review ' + label)
    return value


def _digest(value):
    if not isinstance(value, str) or not re.fullmatch(r'[0-9a-f]{64}', value):
        _fail('License evidence requires a lowercase SHA-256 digest.')


def _relative(value):
    _text(value, 'path')
    path = PurePosixPath(value)
    if not path.parts or path.is_absolute() or path.as_posix() != value or any(p in ('', '.', '..') for p in path.parts) or '\\' in value:
        _fail('License paths must be exact contained relative POSIX paths.')
    return path


def _unique_object(items):
    result = {}
    for key, value in items:
        if key in result:
            _fail('Duplicate JSON key in license manifest: ' + key)
        result[key] = value
    return result


def read_manifest(path):
    with Path(path).open('rb') as stream:
        raw = stream.read(MAX_MANIFEST_BYTES + 1)
    if len(raw) > MAX_MANIFEST_BYTES:
        _fail('License manifest exceeds 16 MiB; split redundant entries before retrying.')
    try:
        value = json.loads(raw, object_pairs_hook=_unique_object)
    except (UnicodeError, ValueError, RecursionError) as exc:
        _fail('Invalid license manifest JSON: ' + type(exc).__name__)
    return value, hashlib.sha256(raw).hexdigest()


def review_context(source, helpers, versions, input_hashes, watchtower_version, warden_version):
    # Preserve application and deployment-helper identities separately. The
    # caller supplies immutable acquisition evidence, never "latest" aliases.
    return {'source': source, 'helpers': {'version': helpers['version'], 'tree_sha256': helpers['tree_sha256']},
            'versions': {'watchtower': watchtower_version, 'warden': warden_version},
            'dependencies': versions, 'dependency_input_hashes': input_hashes}


def payload_files(package):
    """All regular content except notices/review evidence and signing metadata.

The code signatures generated by codesign are covered by the final artifact
inventory, not represented as additional third-party components. Contained
symlink aliases resolve to the same inventoried regular file.
    """
    files = []
    try:
        items = inventory(package)
    except ClosureError as exc:
        raise LicenseCoverageError('Unsafe license/package input: ' + str(exc)) from exc
    for item in items:
        path = PurePosixPath(item['path'])
        if item['type'] != 'file' or path.parts[0] == 'licenses' or path.as_posix() == 'artifact-manifest.json':
            continue
        if (len(path.parts) >= 4 and path.parts[0] in ('watchtower.app', 'Setup.app')
                and path.parts[-2:] == ('_CodeSignature', 'CodeResources')):
            continue
        files.append(item['path'])
    return files


def _evidence(item, package):
    _keys(item, ('path', 'sha256'))
    path = _relative(item['path'])
    if path.parts[0] != 'licenses' or len(path.parts) < 2:
        _fail('Notice/source evidence must be inside the package licenses directory.')
    target = Path(package) / str(path)
    if not contained(target.resolve(), Path(package).resolve() / 'licenses') or not target.is_file() or target.stat().st_size == 0:
        _fail('Missing, empty or escaping license evidence: ' + str(path))
    _digest(item['sha256'])
    if sha256(target) != item['sha256']:
        _fail('License evidence hash mismatch: ' + str(path))


def _source(item, package):
    if not isinstance(item, dict):
        _fail('A component needs immutable source evidence.')
    kind = item.get('kind')
    if kind == 'bundled-source':
        _keys(item, ('kind', 'path', 'sha256'))
        _evidence({k: item[k] for k in ('path', 'sha256')}, package)
        return
    if kind not in ('archive', 'git'):
        _fail('Source evidence kind must be archive, git or bundled-source.')
    identity = 'sha256' if kind == 'archive' else 'commit'
    _keys(item, ('kind', 'url', identity))
    try:
        url = urllib.parse.urlsplit(_text(item['url'], 'source URL'))
    except ValueError:
        _fail('Invalid source URL in license evidence.')
    if url.scheme != 'https' or not url.hostname or url.username or url.password or url.query or url.fragment:
        _fail('Source evidence requires an HTTPS URL without credentials, query or fragment.')
    if kind == 'archive':
        _digest(item['sha256'])
    elif not isinstance(item['commit'], str) or not re.fullmatch(r'(?:[0-9a-f]{40}|[0-9a-f]{64})', item['commit']):
        _fail('Git source evidence needs an exact commit, never a branch or tag alias.')


def validate(document, package, context, accepted=False, production=False):
    _keys(document, ('schema_version', 'context', 'review', 'components'), ('unassigned_paths',))
    if type(document['schema_version']) is not int or document['schema_version'] != SCHEMA_VERSION:
        _fail('Unsupported component license manifest version.')
    if document['context'] != context:
        _fail('License review belongs to different source, helpers or dependencies; review the current template.')
    review = document['review']
    _keys(review, ('status', 'reviewer', 'reviewed_at', 'scope', 'attestation'))
    if any(not isinstance(value, str) for value in review.values()):
        _fail('License review fields must be strings.')
    if review['status'] not in ('draft', 'complete') or review['scope'] != 'all-distributed-content':
        _fail('License review must use draft/complete status and cover all distributed content.')
    if review['status'] == 'complete':
        _text(review['reviewer'], 'reviewer')
        try:
            stamp = datetime.datetime.strptime(review['reviewed_at'], '%Y-%m-%dT%H:%M:%SZ')
        except (TypeError, ValueError):
            _fail('Completed license review requires a UTC reviewed_at timestamp.')
        if stamp > datetime.datetime.utcnow() + datetime.timedelta(minutes=5):
            _fail('License review timestamp is in the future.')
        if review['attestation'] != ATTESTATION:
            _fail('Reviewer must explicitly account for embedded code and all distributed components.')
    paths = set(payload_files(package)); assigned = set(); component_ids = set()
    if not isinstance(document['components'], list):
        _fail('License components must be a list.')
    for component in document['components']:
        _keys(component, ('id', 'version', 'license_expression', 'paths', 'notices', 'source', 'redistribution'))
        identifier = _text(component['id'], 'component ID')
        if identifier in component_ids:
            _fail('Duplicate license component ID: ' + identifier)
        component_ids.add(identifier)
        for key in ('version', 'license_expression'):
            _text(component[key], key)
        if not isinstance(component['paths'], list) or not component['paths']:
            _fail('Every component must identify exact distributed file paths.')
        own_paths = set()
        for value in component['paths']:
            path = str(_relative(value))
            if path not in paths or path in own_paths:
                _fail('Unknown or repeated component payload path: ' + path)
            own_paths.add(path)
        assigned.update(own_paths)
        notices = component['notices']
        if not isinstance(notices, list) or not notices:
            _fail('Each component requires hashed notice evidence.')
        for notice in notices:
            _evidence(notice, package)
        _source(component['source'], package)
        decision = component['redistribution']
        _keys(decision, ('basis', 'source_obligation', 'evidence'))
        _text(decision['basis'], 'redistribution basis')
        if decision['source_obligation'] not in ('none-recorded', 'source-included', 'source-offer', 'other-reviewed'):
            _fail('Record the reviewed source obligation and its supporting evidence.')
        if not isinstance(decision['evidence'], list) or not decision['evidence']:
            _fail('A redistribution decision requires hashed evidence, even when no source obligation is recorded.')
        for evidence in decision['evidence']:
            _evidence(evidence, package)
        if decision['source_obligation'] == 'source-included' and component['source']['kind'] != 'bundled-source':
            _fail('source-included requires bundled source evidence.')
    missing = sorted(paths - assigned)
    if 'unassigned_paths' in document and document['unassigned_paths'] != missing:
        _fail('Unassigned path list is stale; use the current exhaustive coverage report.')
    complete = review['status'] == 'complete' and not missing
    if review['status'] == 'complete' and missing:
        _fail('Completed review leaves payload files without a component mapping.')
    if production and (not complete or not accepted):
        _fail('Production redistribution requires a complete --license-manifest and --accept-licenses; review the generated template.')
    return {'schema_version': SCHEMA_VERSION, 'status': 'complete' if complete else 'unverified',
            'review_type': 'recorded-structural-coverage', 'legal_approval': 'not-inferred',
            'license_decision_accepted': bool(accepted), 'component_count': len(component_ids),
            'payload_file_count': len(paths), 'covered_file_count': len(assigned), 'unassigned_paths': missing,
            'generated_metadata_excluded': ['artifact-manifest.json', 'licenses/**', '**/_CodeSignature/CodeResources']}


def record(package, context, input_path=None, accepted=False, production=False):
    """Write review/report once, before signing, never modify a frozen package."""
    root = Path(package) / 'licenses'
    names = ('COMPONENT-LICENSES.json', 'LICENSE-COVERAGE.json')
    if any((root / name).exists() for name in names):
        _fail('Reserved license review output already exists in input notices; use a clean notice directory.')
    digest = None
    if input_path:
        document, digest = read_manifest(input_path)
    else:
        document = {'schema_version': SCHEMA_VERSION, 'context': context,
                    'review': {'status': 'draft', 'reviewer': '', 'reviewed_at': '',
                               'scope': 'all-distributed-content', 'attestation': ''},
                    'components': [], 'unassigned_paths': payload_files(package)}
    # Always retain the draft/report before blocking missing production review.
    report = validate(document, package, context, accepted=accepted)
    report['input_sha256'] = digest
    for name, value in zip(names, (document, report)):
        path = root / name
        path.write_text(json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + '\n')
        path.chmod(0o644)
    if production and (report['status'] != 'complete' or not accepted):
        _fail('Production license review is incomplete; finish ' + str(root / names[0]) + ' and supply --license-manifest with --accept-licenses.')
    return report
